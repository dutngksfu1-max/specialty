/**
 * 결과 프로필 16개 (contentVersion 5.0.0 — DEC-068 직설적 결과 문장 개편)
 *
 * 축 4개 × 방향 2가지 = 2⁴ = 16개 조합입니다. 하나도 빠뜨리면 안 됩니다.
 * `key`는 내부 식별자일 뿐 화면에 노출하지 않습니다. 사용자에게는 `title`만 보입니다.
 *
 * 자리 순서는 axes 배열 순서입니다.
 *   1번째 = axis-energy    p 교류형   / n 몰입형
 *   2번째 = axis-lens      p 실제형   / n 가능성형
 *   3번째 = axis-decision  p 원칙형   / n 맥락형
 *   4번째 = axis-rhythm    p 계획형   / n 유연형
 *
 * 표현 규칙 (docs/content/teacher-style-v1.md 6.3)
 *   - "궁합", 등급·순위·백분위, 낙인이 되는 말을 쓰지 않습니다
 *   - "당신은 ~형입니다" 대신 "~하는 편이에요 / ~할 때가 많아요"
 *   - `needsTuning`은 "맞지 않는다"가 아니라 "이렇게 이야기해 두면 서로 편해진다"는 뜻입니다.
 *     그래서 항목마다 구체적인 조율 방법을 한 문장 붙였습니다
 *
 * 3.0.0에서 늘어난 것
 *   - shiningMoments / underPressure / withColleagues 에 **장면(scene)** 이 붙습니다.
 *     선생님이 필요한 장면만 골라 읽을 수 있게 하려는 것입니다.
 *   - nextSteps — 성향 서술이 아니라 내일 실제로 해 볼 수 있는 행동
 *   - talkingPoints — 연수에서 옆 사람과 나눌 질문
 */

const P = "positive";
const N = "negative";

function poles(energy: string, lens: string, decision: string, rhythm: string) {
  return {
    "axis-energy": energy,
    "axis-lens": lens,
    "axis-decision": decision,
    "axis-rhythm": rhythm,
  };
}

